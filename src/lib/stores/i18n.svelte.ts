export const i18n = {
  get lang() {
    return _lang;
  },
  set lang(l: Language) {
    _lang = l;
    if (browser) {
      localStorage.setItem('dozeforge_lang', l);
    }
  },
  toggle() {
    this.lang = this.lang === 'en' ? 'es' : 'en';
  },
  // The translation function
  t(key: string, ...args: any[]): string {
    const dict = translations[_lang];
    if (!dict) return key; // Safety fallback
    
    let result = dict[key] || key;

    if (args.length > 0) {
      const first = args[0];
      if (first && typeof first === 'object' && !Array.isArray(first)) {
        // Named interpolation: {{name}} → value from the params object.
        for (const [name, value] of Object.entries(first)) {
          result = result.replace(new RegExp(`\\{\\{\\s*${name}\\s*\\}\\}`, 'g'), String(value));
        }
      } else {
        // Positional interpolation: {0}, {1}, …
        args.forEach((arg, i) => {
          result = result.replace(new RegExp(`\\{${i}\\}`, 'g'), String(arg));
        });
      }
    }

    return result;
  }
};
